  or abs(grams*t.protein_per_100g-i.portion_g*s.protein_per_100g)>greatest(200,i.portion_g*s.protein_per_100g*.2)+0.000001
  or abs(grams*t.carbs_per_100g-i.portion_g*s.carbs_per_100g)>greatest(300,i.portion_g*s.carbs_per_100g*.2)+0.000001
  or abs(grams*t.fat_per_100g-i.portion_g*s.fat_per_100g)>greatest(150,i.portion_g*s.fat_per_100g*.2)+0.000001 then raise exception 'Essa troca não mantém os nutrientes e a porção próximos do plano. Fale com o suporte da nutri.';end if;
