create table public.taco_foods (
 id integer primary key, name text not null, category text not null,
 kcal_per_100g numeric check(kcal_per_100g>=0),source_version text not null default 'TACO-4-2011'
);
alter table public.taco_foods enable row level security;
revoke all on public.taco_foods from anon,authenticated;
grant select on public.taco_foods to anon,authenticated;
create policy taco_public_reference on public.taco_foods for select to anon,authenticated using(true);

alter table public.diet_items add column taco_food_id integer references public.taco_foods(id),add column portion_g numeric;
alter table public.diet_items add constraint diet_item_taco_portion check(
 (taco_food_id is null and portion_g is null) or (taco_food_id is not null and portion_g is not null and portion_g>0 and portion_g<=100000)
);

create table public.patient_food_substitutions (
 id uuid primary key,patient_id uuid not null references public.profiles(id) on delete cascade,
 meal_id uuid not null references public.diet_meals(id) on delete cascade,
 item_id uuid not null references public.diet_items(id) on delete cascade,check_date date not null,
 source_food_id integer not null references public.taco_foods(id),target_food_id integer not null references public.taco_foods(id),
 original_name text not null,original_quantity text,source_name text not null,target_name text not null,
 source_grams numeric not null check(source_grams>0),target_grams numeric not null check(target_grams>0),
 source_kcal_per_100g numeric not null,target_kcal_per_100g numeric not null,energy_kcal numeric not null,
 source_version text not null default 'TACO-4-2011',created_at timestamptz not null default now(),
 unique(patient_id,item_id,check_date)
);
create index food_substitution_patient_date on public.patient_food_substitutions(patient_id,check_date);
create index food_substitution_meal on public.patient_food_substitutions(meal_id);
alter table public.patient_food_substitutions enable row level security;
revoke all on public.patient_food_substitutions from anon,authenticated;
grant select on public.patient_food_substitutions to authenticated;
create policy substitution_read on public.patient_food_substitutions for select to authenticated
 using(patient_id=(select public.current_profile_id()) or (select public.is_clinic_staff()));
create trigger clinic_audit_change after insert or update or delete on public.patient_food_substitutions for each row execute function public.clinic_audit_change();

create function public.save_food_substitution(p_operation uuid,p_item uuid,p_target integer,p_date date,p_expected uuid default null)
 returns jsonb language plpgsql security definer set search_path='' as $$
declare actor uuid:=public.current_profile_id();i public.diet_items;s public.taco_foods;t public.taco_foods;
 pid uuid;diet_status text;current_row public.patient_food_substitutions;history public.clinical_records;day date:=(now() at time zone 'America/Sao_Paulo')::date;
begin
 if actor is null or p_operation is null then raise exception 'Autenticação necessária' using errcode='42501';end if;
 select * into i from public.diet_items where id=p_item;
 select d.patient_id,d.status into pid,diet_status from public.diets d join public.diet_meals m on m.diet_id=d.id where m.id=i.meal_id;
 if pid is distinct from actor then raise exception 'Alimento não autorizado' using errcode='42501';end if;
 if p_date is distinct from day or diet_status<>'active' then raise exception 'Escolha um alimento do seu plano atual para hoje';end if;
 perform pg_advisory_xact_lock(hashtextextended(pid::text||i.meal_id::text||p_date::text,0));
 select * into current_row from public.patient_food_substitutions where patient_id=pid and item_id=i.id and check_date=p_date for update;
 select * into history from public.clinical_records where id=p_operation;
 if found then
  if history.created_by is distinct from actor or history.kind<>'checkin' or history.payload->>'category' is distinct from 'meal_substitution' or history.payload->>'action' is distinct from 'replace' or history.payload->>'item_id' is distinct from p_item::text or history.payload->>'target_food_id' is distinct from p_target::text or history.payload->>'date' is distinct from p_date::text then raise exception 'Identificador de envio já utilizado';end if;
  return jsonb_build_object('substitution',case when current_row.id is null then null else to_jsonb(current_row) end,'replayed',true);
 end if;
 if current_row.id is distinct from p_expected then raise exception 'A troca foi alterada em outra janela. Atualize antes de continuar.' using errcode='40001';end if;
 select * into s from public.taco_foods where id=i.taco_food_id;select * into t from public.taco_foods where id=p_target;
 if s.id is null or t.id is null or coalesce(i.portion_g,0)<=0 or coalesce(s.kcal_per_100g,0)<=0 or coalesce(t.kcal_per_100g,0)<=0 or s.id=t.id then raise exception 'Não há referência e peso válidos para esta troca';end if;
 insert into public.patient_food_substitutions(id,patient_id,meal_id,item_id,check_date,source_food_id,target_food_id,original_name,original_quantity,source_name,target_name,source_grams,target_grams,source_kcal_per_100g,target_kcal_per_100g,energy_kcal)
 values(p_operation,pid,i.meal_id,i.id,p_date,s.id,t.id,i.food_name,concat_ws(' ',nullif(i.quantity,''),nullif(i.unit,'')),s.name,t.name,i.portion_g,i.portion_g*s.kcal_per_100g/t.kcal_per_100g,s.kcal_per_100g,t.kcal_per_100g,i.portion_g*s.kcal_per_100g/100)
 on conflict(patient_id,item_id,check_date) do update set id=excluded.id,target_food_id=excluded.target_food_id,target_name=excluded.target_name,target_grams=excluded.target_grams,target_kcal_per_100g=excluded.target_kcal_per_100g,created_at=now()
 returning * into current_row;
 -- A planned replacement does not claim that the patient already ate it.
 delete from public.patient_item_checks where patient_id=pid and item_id=i.id and check_date=p_date;
 insert into public.clinical_records(id,patient_id,kind,payload,created_by)
 values(p_operation,pid,'checkin',to_jsonb(current_row)||jsonb_build_object('category','meal_substitution','action','replace','date',p_date),actor);
 return jsonb_build_object('substitution',to_jsonb(current_row),'replayed',false);
end $$;
revoke all on function public.save_food_substitution(uuid,uuid,integer,date,uuid) from public,anon;
grant execute on function public.save_food_substitution(uuid,uuid,integer,date,uuid) to authenticated;

create function public.remove_food_substitution(p_id uuid,p_operation uuid) returns boolean language plpgsql security definer set search_path='' as $$
declare actor uuid:=public.current_profile_id();r public.patient_food_substitutions;staff boolean:=public.is_clinic_staff();begin
 if actor is null or p_operation is null then raise exception 'Autenticação necessária' using errcode='42501';end if;
 select * into r from public.patient_food_substitutions where id=p_id;
 if not found then return false;end if;
 if r.patient_id<>actor and not staff then raise exception 'Troca não autorizada' using errcode='42501';end if;
 if not staff and r.check_date<>(now() at time zone 'America/Sao_Paulo')::date then raise exception 'Só é possível desfazer a troca de hoje';end if;
 perform pg_advisory_xact_lock(hashtextextended(r.patient_id::text||r.meal_id::text||r.check_date::text,0));
 delete from public.patient_food_substitutions where id=p_id;
 if not found then return false;end if;
 delete from public.patient_item_checks where patient_id=r.patient_id and item_id=r.item_id and check_date=r.check_date;
 insert into public.clinical_records(id,patient_id,kind,payload,created_by)
 values(p_operation,r.patient_id,'checkin',to_jsonb(r)||jsonb_build_object('category','meal_substitution','action','restore','date',r.check_date),actor);
 return true;
end $$;
revoke all on function public.remove_food_substitution(uuid,uuid) from public,anon;
grant execute on function public.remove_food_substitution(uuid,uuid) to authenticated;

create or replace function public.save_diet_version(p_diet uuid,p_payload jsonb) returns uuid language plpgsql security definer set search_path='' as $$
declare old_d public.diets;new_id uuid;m jsonb;o jsonb;i jsonb;mid uuid;mi int:=0;ii int;opts jsonb;begin
 if not public.is_clinic_staff() then raise exception 'Permissão negada' using errcode='42501';end if;
 select * into old_d from public.diets where id=p_diet for update;if not found then raise exception 'Plano não encontrado';end if;
 perform pg_advisory_xact_lock(hashtextextended(old_d.patient_id::text,0));
 if coalesce(p_payload->>'status','') not in ('draft','active') or jsonb_typeof(p_payload->'meals') is distinct from 'array' or nullif(trim(p_payload->>'title'),'') is null or jsonb_array_length(p_payload->'meals')>50 then raise exception 'Revise o plano alimentar';end if;
 if p_payload->>'status'='active' and jsonb_array_length(p_payload->'meals')=0 then raise exception 'Adicione pelo menos uma refeição';end if;
 if p_payload->>'status'='active' then update public.diets set status='archived',retired_at=now() where patient_id=old_d.patient_id and status='active';end if;
 insert into public.diets(patient_id,title,notes,start_date,status,created_by,previous_version_id,published_at) values(old_d.patient_id,p_payload->>'title',p_payload->>'notes',nullif(p_payload->>'start_date','')::date,p_payload->>'status',public.current_profile_id(),old_d.id,case when p_payload->>'status'='active' then now() end) returning id into new_id;
 for m in select value from jsonb_array_elements(p_payload->'meals') loop
 if nullif(trim(m->>'name'),'') is null then raise exception 'Dê um nome para cada refeição';end if;
 opts:=coalesce(m->'options',jsonb_build_array(jsonb_build_object('name','Opção A','items',coalesce(m->'items','[]'))));
 if jsonb_typeof(opts)<>'array' or jsonb_array_length(opts)=0 or jsonb_array_length(opts)>30 then raise exception 'Revise as opções da refeição';end if;
 if exists(select 1 from jsonb_array_elements(opts) x group by trim(x->>'name') having count(*)>1) then raise exception 'Use nomes diferentes nas opções da mesma refeição';end if;
 insert into public.diet_meals(diet_id,name,scheduled_time,notes,sort_order,options) values(new_id,trim(m->>'name'),nullif(m->>'scheduled_time','')::time,m->>'notes',mi,(select jsonb_agg(jsonb_build_object('name',x->>'name','notes',x->>'notes')) from jsonb_array_elements(opts)x)) returning id into mid;mi:=mi+1;ii:=0;
 -- Common prescribed foods are stored once, with no alternative name.
 if jsonb_typeof(coalesce(m->'shared_items','[]'))<>'array' or jsonb_array_length(coalesce(m->'shared_items','[]'))>100 then raise exception 'Revise os alimentos da refeição';end if;
 for i in select value from jsonb_array_elements(coalesce(m->'shared_items','[]')) loop
 if nullif(trim(i->>'food_name'),'') is not null then insert into public.diet_items(meal_id,food_name,quantity,unit,notes,substitutions,sort_order,option_name,taco_food_id,portion_g) values(mid,trim(i->>'food_name'),i->>'quantity',i->>'unit',i->>'notes',i->>'substitutions',ii,null,nullif(i->>'taco_food_id','')::integer,nullif(i->>'portion_g','')::numeric);ii:=ii+1;end if;end loop;
 for o in select value from jsonb_array_elements(opts) loop
 if nullif(trim(o->>'name'),'') is null or jsonb_typeof(o->'items') is distinct from 'array' or jsonb_array_length(o->'items')>100 then raise exception 'Revise as opções e alimentos';end if;
 if p_payload->>'status'='active' and not exists(select 1 from jsonb_array_elements(o->'items') x where nullif(trim(x->>'food_name'),'') is not null) then raise exception 'Cada opção precisa de um alimento para publicar';end if;
 for i in select value from jsonb_array_elements(o->'items') loop
 if nullif(trim(i->>'food_name'),'') is not null then insert into public.diet_items(meal_id,food_name,quantity,unit,notes,substitutions,sort_order,option_name,taco_food_id,portion_g) values(mid,trim(i->>'food_name'),i->>'quantity',i->>'unit',i->>'notes',i->>'substitutions',ii,trim(o->>'name'),nullif(i->>'taco_food_id','')::integer,nullif(i->>'portion_g','')::numeric);ii:=ii+1;end if;end loop;end loop;end loop;
 if old_d.status='draft' then update public.diets set status='archived' where id=old_d.id;end if;
 insert into public.care_audit(table_name,record_id,actor_id,action) values('diets',new_id,auth.uid(),'version_created');
 if p_payload->>'status'='active' then insert into public.care_notifications(patient_id,title,body,source_key) values(old_d.patient_id,'Novo plano alimentar','Seu plano foi atualizado pela nutricionista.','diet:'||new_id);end if;return new_id;end $$;

